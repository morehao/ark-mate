package store

// 本文件是 **v29**（会话**钉住**自己的原生权限模式）的版本步本体（P1-f 下半 / ADR-16①）。
//
// 为什么必须**落库**而不是每次现算：原生权限模式只能以**进程 env**（`DSH_PERMISSION_MODE`）
// 下发——探针实测 `/permission` 命令面在 ACP 上不存在，所以"一个进程内按会话切换模式"这条路
// 走不通，只能退化成**每模式一个暖进程**。而暖进程的键必须包含这个模式，于是模式必须在**取连接
// 之前**就已知。
//
// 由此得到本列的两条语义（与 `capability_json` 同款）：
//
//	① 它是**创建时的快照**：建会话时按「显式 > 工作空间默认 > 平台缺省」解析一次就钉住。
//	   每次现算工作空间默认的后果是——用户改了工作空间的默认权限模式，**昨天那些会话**的行为
//	   跟着变了，而界面上什么都不会说；
//	② 空串 = **不注入**（平台缺省）。刻意不物化那个缺省值：物化它等于在库里复制一份平台缺省的
//	   事实源，两边迟早不一致。
var migrationV29 = migration{
	version: 29,
	name:    "会话钉住原生权限模式（native_mode；空 = 不注入）",
	// 纯增列（有 DEFAULT），不需要备份。
	statements: []string{
		`ALTER TABLE sessions ADD COLUMN native_mode TEXT NOT NULL DEFAULT ''`,
	},
}
