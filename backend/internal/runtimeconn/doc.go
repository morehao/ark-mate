// Package runtimeconn 是**执行面**：把会话挂到「本进程认的那个底座」上。
//
// 它**负责**：底座身份与进程状态（`Binding`）、连接池与代际键（`Pool` / `Conn`）、子进程登记
// 与回收、空闲回收、以及运行期诊断（stderr 尾巴 / 最近失败 / 归属歧义留痕）。
//
// 它**不负责**：会话记录与轮次（`domain/session`——那边持**记录**，这边持**连接**）、
// 能力定义与投放（`domain/{skill,mcp,provider}`）、事件的落库与铸号（`domain/session/publish.go`
// 是唯一铸号点）、以及**会话状态的收尾**（连接被摘除之后怎么改会话/在途/诊断，经 `DropSink`
// 交回编排侧应用——本域不认识会话表）。
//
// **切线与锁**：`ActiveSession` 活动集与会话记录都不在本域；本域只按句柄查连接。
// 池自持一把只保护连接表的锁，**绝不在自己的锁下**调会话侧或编排侧（`DropSink` 的两个方法
// 都在池锁之外调用）——这条纪律的反面是锁序反转，而它的表现是 `go test ./...` **挂死**、
// 不是红（计划 §10.5.3 教训 1）。
